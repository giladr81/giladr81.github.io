/* Small inline-SVG chart helpers + data binding. No dependencies.
   Numbers on pages come from window.REVIEWS / window.BC_META (generated by build/*.py), never hand-typed. */
(function () {
  const NS = "http://www.w3.org/2000/svg";
  function el(tag, attrs, parent) {
    const n = document.createElementNS(NS, tag);
    for (const k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }
  function txt(parent, x, y, s, attrs) { const t = el("text", Object.assign({ x, y }, attrs || {}), parent); t.textContent = s; return t; }

  // Shared tooltip
  let tip;
  function showTip(e, html) {
    if (!tip) { tip = document.createElement("div"); tip.className = "tip"; tip.setAttribute("role", "status"); document.body.appendChild(tip); }
    tip.innerHTML = html; tip.hidden = false;
    const pad = 12, w = tip.offsetWidth, h = tip.offsetHeight;
    let x = e.clientX + pad, y = e.clientY + pad;
    if (x + w > innerWidth - 8) x = e.clientX - w - pad;
    if (y + h > innerHeight - 8) y = e.clientY - h - pad;
    tip.style.left = x + "px"; tip.style.top = y + "px";
  }
  function hideTip() { if (tip) tip.hidden = true; }
  function hover(node, html) {
    node.addEventListener("mousemove", (e) => showTip(e, html));
    node.addEventListener("mouseleave", hideTip);
    node.addEventListener("focus", () => { const r = node.getBoundingClientRect(); showTip({ clientX: r.right, clientY: r.top }, html); });
    node.addEventListener("blur", hideTip);
    node.setAttribute("tabindex", "0");
  }

  // Paired horizontal bars: rows [{label, a, b, aLabel, bLabel, note}]; a = highlight, b = benchmark.
  function pairedBars(container, rows, o) {
    o = Object.assign({ w: 760, rowH: 46, left: 170, right: 96, max: null, unit: "", aName: "A", bName: "B" }, o || {});
    const max = o.max || Math.max(...rows.flatMap((r) => [r.a, r.b])) * 1.08;
    const H = rows.length * o.rowH + 34, plotW = o.w - o.left - o.right;
    const svg = el("svg", { viewBox: `0 0 ${o.w} ${H}`, role: "img", "aria-label": o.aria || "", class: "wide" });
    const x = (v) => o.left + (v / max) * plotW;
    const ticks = o.ticks || [0, max / 2, max].map((t) => Math.round(t));
    ticks.forEach((t) => { el("line", { x1: x(t), x2: x(t), y1: 4, y2: H - 26, class: "grid" }, svg); txt(svg, x(t), H - 8, t + o.unit, { "text-anchor": "middle" }); });
    txt(svg, o.w - o.right + 12, 12, o.ratioHead || "Ratio", { "font-size": 11 });
    rows.forEach((r, i) => {
      const y0 = 18 + i * o.rowH, g = el("g", { class: "row" }, svg);
      txt(g, o.left - 12, y0 + 17, r.label, { class: "lab", "text-anchor": "end" });
      const ha = 13, hb = 9;
      el("rect", { x: o.left, y: y0 + 2, width: Math.max(2, x(r.a) - o.left), height: ha, rx: 2, class: "hl" }, g);
      el("rect", { x: o.left, y: y0 + 2 + ha + 3, width: Math.max(2, x(r.b) - o.left), height: hb, rx: 2, class: "bm" }, g);
      txt(g, x(r.a) + 6, y0 + 13, r.aLabel ?? r.a, { fill: "currentColor" });
      const ratio = r.b > 0 ? (r.a / r.b) : null;
      txt(g, o.w - o.right + 12, y0 + 18, ratio ? ratio.toFixed(1) + "×" : "n/a", { class: "lab", "font-family": "var(--font-data)", "font-weight": 600 });
      const hit = el("rect", { x: 0, y: y0 - 4, width: o.w, height: o.rowH, class: "hit" }, g);
      hover(hit, `<b>${r.label}</b><br>${o.aName}: ${r.a}${o.unit}<br>${o.bName}: ${r.b}${o.unit}${r.note ? "<br>" + r.note : ""}`);
    });
    container.appendChild(svg);
  }

  // Vertical columns, single series, with optional highlighted index and annotation.
  function columns(container, data, o) {
    o = Object.assign({ w: 520, h: 220, top: 26, bottom: 34, left: 40, right: 10, fmt: (v) => v, max: null, highlight: [], annotate: null }, o || {});
    const max = o.max || Math.max(...data.map((d) => d.value)) * 1.15 || 1;
    const svg = el("svg", { viewBox: `0 0 ${o.w} ${o.h}`, role: "img", "aria-label": o.aria || "" });
    const plotH = o.h - o.top - o.bottom, plotW = o.w - o.left - o.right, bw = plotW / data.length;
    const y = (v) => o.top + plotH - (v / max) * plotH;
    (o.ticks || [0, max / 2, max]).forEach((t) => { el("line", { x1: o.left, x2: o.w - o.right, y1: y(t), y2: y(t), class: "grid" }, svg); txt(svg, o.left - 6, y(t) + 4, o.fmt(t), { "text-anchor": "end" }); });
    data.forEach((d, i) => {
      const cx = o.left + i * bw, w = Math.min(28, bw * 0.62), hl = o.highlight.includes(i);
      const r = el("rect", { x: cx + (bw - w) / 2, y: y(d.value), width: w, height: Math.max(1, y(0) - y(d.value)), rx: 2, class: hl ? "hl" : "bm" }, svg);
      if (d.label) txt(svg, cx + bw / 2, d.sub != null ? o.h - 20 : o.h - 12, d.label, { "text-anchor": "middle", "font-size": 11 });
      if (d.sub) txt(svg, cx + bw / 2, o.h - 5, d.sub, { "text-anchor": "middle", "font-size": 10 });
      if (hl) txt(svg, cx + bw / 2, y(d.value) - 6, o.fmt(d.value), { "text-anchor": "middle", class: "lab", "font-family": "var(--font-data)" });
      const hit = el("rect", { x: cx, y: o.top, width: bw, height: plotH, class: "hit" }, svg);
      hover(hit, d.tip || `${d.label}: ${o.fmt(d.value)}`);
    });
    if (o.annotate) txt(svg, o.annotate.x, o.annotate.y, o.annotate.text, { class: "lab", "font-size": 12 });
    container.appendChild(svg);
  }

  // Ranked horizontal bars, single series.
  function ranked(container, data, o) {
    o = Object.assign({ w: 520, rowH: 28, left: 110, right: 40 }, o || {});
    const max = Math.max(...data.map((d) => d.value)) || 1, H = data.length * o.rowH + 6;
    const svg = el("svg", { viewBox: `0 0 ${o.w} ${H}`, role: "img", "aria-label": o.aria || "" });
    const x = (v) => o.left + (v / max) * (o.w - o.left - o.right);
    data.forEach((d, i) => {
      const y0 = 4 + i * o.rowH;
      txt(svg, o.left - 10, y0 + 15, d.label, { class: "lab", "text-anchor": "end" });
      el("rect", { x: o.left, y: y0 + 5, width: Math.max(2, x(d.value) - o.left), height: 12, rx: 2, class: i === 0 ? "hl" : "bm" }, svg);
      txt(svg, x(d.value) + 6, y0 + 15, d.value, {});
    });
    container.appendChild(svg);
  }

  // Data binding: <span data-k="ios_comparison.gaia.low_share" data-fmt="pct"></span>
  function get(obj, path) { return path.split(".").reduce((a, k) => (a == null ? a : a[k]), obj); }
  const FMT = {
    pct: (v) => Math.round(v * 100) + "%",
    pct1: (v) => (v * 100).toFixed(1) + "%",
    x: (v) => v.toFixed(1) + "×",
    n: (v) => Number(v).toLocaleString("en-CA"),
    raw: (v) => v,
    date: (v) => { const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(v)); if (!m) return v;
      return `${["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"][+m[2] - 1]} ${+m[3]}, ${m[1]}`; },
  };
  function bind(root, data) {
    root.querySelectorAll("[data-k]").forEach((n) => {
      const v = get(data, n.dataset.k);
      if (v == null) { n.textContent = "?"; console.warn("missing data key", n.dataset.k); return; }
      n.textContent = (FMT[n.dataset.fmt || "raw"])(v);
    });
  }
  // Quotes: <blockquote data-q="key"> filled from REVIEWS.quotes (verbatim excerpts, verified at build time).
  function quotes(root, Q) {
    const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
    root.querySelectorAll("[data-q]").forEach((n) => {
      const q = Q[n.dataset.q]; if (!q) { console.warn("missing quote", n.dataset.q); return; }
      const [y, m, d] = q.date.split("-");
      n.innerHTML = "";
      const p = document.createElement("p"); p.textContent = "\u201c" + q.text + "\u201d";
      const c = document.createElement("footer");
      c.textContent = `${q.app} review, ${q.store}, ${months[+m - 1]} ${+d} ${y}, ${q.rating} star${q.rating > 1 ? "s" : ""}`;
      n.append(p, c);
    });
  }
  window.Charts = { pairedBars, columns, ranked, bind, hover, el, quotes };
})();
